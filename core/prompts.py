def get_system_prompt() -> str:
    return SYSTEM_PROMPT


def get_user_prompt(mode: str, text: str) -> str:
    """Получить пользовательский промпт для режима."""
    if mode not in MODE_PROMPTS:
        raise ValueError(f"Неизвестный режим: {mode}. Доступные: {list(MODE_PROMPTS.keys())}")
    return MODE_PROMPTS[mode]["user"].format(text=text)


def get_map_prompt(mode: str, text: str) -> str:
    """Получить map-промпт для обработки чанка."""
    if mode not in MODE_PROMPTS:
        raise ValueError(f"Неизвестный режим: {mode}")
    return MODE_PROMPTS[mode]["map"].format(text=text)


def get_reduce_prompt(mode: str, fragments: str) -> str:
    """Получить reduce-промпт для объединения результатов."""
    if mode not in MODE_PROMPTS:
        raise ValueError(f"Неизвестный режим: {mode}")
    return MODE_PROMPTS[mode]["reduce"].format(fragments=fragments)


def get_mode_title(mode: str) -> str:
    """Получить название режима."""
    if mode in MODE_PROMPTS:
        return MODE_PROMPTS[mode]["title"]
    return mode
